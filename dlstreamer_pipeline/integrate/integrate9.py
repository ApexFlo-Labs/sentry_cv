    def count_in(_pad, _info, cam):
        cam["in"] += 1
        if not cam["seen"]:
            send(cam, ("status", "healthy", "none"), droppable=False)  # first frame after a (re)build
        cam["last"], cam["seen"], cam["wait"] = time.time(), True, 1
        return Gst.PadProbeReturn.OK

    def drop_eos(_pad, info, _data):
        if info.get_event().type == Gst.EventType.EOS:
            return Gst.PadProbeReturn.DROP
        return Gst.PadProbeReturn.OK

    def start(cam):
        desc = (f"urisourcebin uri={cam['url']} ! decodebin3 ! vapostproc ! video/x-raw(memory:VAMemory),format=NV12 "
                f"! videorate drop-only=true skip-to-first=true ! video/x-raw(memory:VAMemory),framerate={cam['fps']}/1 ! tee name=t ! "
                "queue name=tail leaky=downstream max-size-buffers=4 "
                "t. ! queue leaky=downstream max-size-buffers=2 ! videorate drop-only=true skip-to-first=true max-rate=2 ! vapostproc add-borders=true "
                "! video/x-raw,format=BGRx,width=320,height=320 ! videoconvert ! video/x-raw,format=BGR ! queue name=firetail leaky=downstream max-size-buffers=2")
        cam["bin"] = Gst.parse_bin_from_description(desc, False)
        cam["bin"].add_pad(Gst.GhostPad.new("src", cam["bin"].get_by_name("tail").get_static_pad("src")))
        cam["bin"].add_pad(Gst.GhostPad.new("fire", cam["bin"].get_by_name("firetail").get_static_pad("src")))
        pipeline.add(cam["bin"])
        src = cam["bin"].get_static_pad("src")
        cg.creader_attach_in(cam["creader"], ctypes.c_void_p(hash(src)))  # frame counting in C
        src.add_probe(Gst.PadProbeType.EVENT_DOWNSTREAM, drop_eos, None)
        cam["bin"].get_static_pad("fire").add_probe(Gst.PadProbeType.EVENT_DOWNSTREAM, drop_eos, None)
        cam["sink"], cam["fsink"] = cam["mux"].get_static_pad("sink"), cam["fmux"].get_static_pad("sink")
        for pad, sink in ((src, cam["sink"]), (cam["bin"].get_static_pad("fire"), cam["fsink"])):
            result = pad.link(sink)
            if result != Gst.PadLinkReturn.OK:
                log(f"{cam['name']}: link failed: {result.value_nick}")
        cam["t0"], cam["seen"] = time.time(), False
        cam["in_at_start"] = int(cam["hdr"][3])
        cam["bin"].sync_state_with_parent()

    def stream_ready(url):
        u = urlparse(url)
        try:
            with socket.create_connection((u.hostname, u.port or 554), timeout=1) as conn:
                conn.settimeout(1)
                conn.sendall(f"DESCRIBE {url} RTSP/1.0\r\nCSeq: 1\r\nAccept: application/sdp\r\n\r\n".encode())
                return conn.recv(64).split()[1] in (b"200", b"401")
        except (OSError, IndexError):
            return False

    def remove(cam, why):
        t0 = time.time()
        src = cam["bin"].get_static_pad("src")
        cam["bin"].set_state(Gst.State.NULL)
        src.unlink(cam["sink"])
        cam["bin"].get_static_pad("fire").unlink(cam["fsink"])
        pipeline.remove(cam["bin"])
        cam["bin"], cam["sink"], cam["fsink"] = None, None, None
        cam["retry_at"] = time.time() + cam["wait"]
        cam["wait"] = min(10, cam["wait"] * 2)
        send(cam, ("status", "unavailable", "stream_disconnected"), droppable=False)
        log(f"{cam['name']}: removed ({why}) in {(time.time() - t0) * 1000:.0f} ms")

    def watchdog():
        now = time.time()
        for cam in cams:  # what the Python count_in probe did, from the C counters (once per second)
            frames_in = int(cam["hdr"][3])
            if cam["bin"] is not None and frames_in > cam["in_at_start"] and frames_in != cam.get("in_last_seen", -1):
                cam["last"], cam["wait"] = now, 1
                if not cam["seen"]:
                    cam["seen"] = True
                    send(cam, ("status", "healthy", "none"), droppable=False)
            cam["in_last_seen"] = frames_in
        for cam in cams:
            if cam["bin"] is None:
                if now >= cam["retry_at"]:
                    if stream_ready(cam["url"]):
                        t0 = time.time()
                        cam["rebuilds"] += 1
                        cam["grace"] = FIRST_FRAME
                        start(cam)
                        log(f"{cam['name']}: stream back, rebuilt in {(time.time() - t0) * 1000:.0f} ms")
                    else:
                        cam["retry_at"] = now + cam["wait"]
                        cam["wait"] = min(10, cam["wait"] * 2)
                continue
            if now - max(cam["last"], cam["t0"]) > (TIMEOUT if cam["seen"] else cam["grace"]):
                remove(cam, "no frames")
        return True

