    def reader(cam):
        held = {}  # pts -> pix sample, when the two appsinks are not in step
        while not stop_readers.is_set():
            sample = cam["evt"].emit("try-pull-sample", 20 * Gst.MSECOND)
            fire = cam["fevt"].emit("try-pull-sample", 0)
            if sample is not None:
                t0 = time.perf_counter()
                cam["out"] += 1
                cam["frame_count"] += 1
                cam["index"] += 1
                pts = int(sample.get_buffer().pts)
                if steady["t"] is not None and pts >= 0:  # frame arrival (stream timestamp) -> here: decode, detect, track, classify
                    clk = pipeline.get_clock()
                    if clk is not None:
                        cam["glat"].append((clk.get_time() - pipeline.get_base_time() - pts) / 1e6)
                rt = cam.setdefault("rt", {})

                def mark(key, since):
                    now_ = time.perf_counter()
                    rt[key] = rt.get(key, 0.0) + (now_ - since) * 1000
                    return now_
                tt = time.perf_counter()
                pix = held.pop(pts, None)
                while pix is None:
                    got = cam["pix"].emit("try-pull-sample", 50 * Gst.MSECOND)
                    if got is None:
                        break
                    p_pts = int(got.get_buffer().pts)
                    if p_pts == pts:
                        pix = got
                    elif p_pts > pts:
                        held[p_pts] = got
                        break
                while len(held) > 8:
                    held.pop(min(held))
                tt = mark("wait_pix", tt)
                try:
                    detections, candidates = results_from_json(sample)
                    tt = mark("boxes_faces", tt)
                    if pix is not None:
                        shm_name, slot, width, height = write_frame(cam, pix, cam["index"])
                        tt = mark("copy", tt)
                        cam["last_slot"] = (shm_name, slot, cam["index"])
                    else:
                        cam["no_pixels"] += 1
                        s = sample.get_caps().get_structure(0)
                        shm_name, slot, width, height = None, None, int(s.get_value("width")), int(s.get_value("height"))
                    cam["size"] = (width, height)
                    evaluated = (cam["frame_count"] - 1) % FACE_INTERVAL == 0
                    send(cam, ("main", cam["index"], time.time(), shm_name, slot, width, height, detections, evaluated, candidates))
                    mark("send", tt)
                except Exception as exc:
                    log(f"{cam['name']}: reader error: {type(exc).__name__}: {exc}")
                cam["reader_ms"] += (time.perf_counter() - t0) * 1000
            if fire is not None and cam["size"] is not None:
                cam["fire"] += 1
                width, height = cam["size"]
                detections = unletterbox(hazards_from_sample(fire), width, height)
                shm_name, slot, index = cam["last_slot"] if cam["last_slot"] else (None, None, cam["index"])
                send(cam, ("fire", index, time.time(), shm_name, slot, width, height, detections))

