    def faces_from_sample(sample):
        """Her DlsFaceMetadataBridge.probe logic on the appsink sample; our AdaFace tensor has no 'feat' name, so any 512-value tensor."""
        from gstgva import VideoFrame
        frame = VideoFrame(sample.get_buffer(), caps=sample.get_caps())
        regions = list(frame.regions())
        faces = [r for r in regions if r.label() == "face"]
        if not faces:
            return []
        people = [r for r in regions if r.label() == "person"]
        out = []
        for face in faces:
            feature = None
            for tensor in face.tensors():
                data = tensor.data()
                if data is not None and int(data.size) == 512:
                    feature = np.asarray(data, dtype=np.float32).reshape(-1).copy()
                    break
            if feature is None or not np.isfinite(feature).all() or float(np.linalg.norm(feature)) <= 1e-12:
                continue
            feature /= float(np.linalg.norm(feature))
            fr = face.rect()
            cx, cy = fr.x + fr.w / 2.0, fr.y + fr.h / 2.0
            owners = [p for p in people if p.rect().x <= cx <= p.rect().x + p.rect().w and p.rect().y <= cy <= p.rect().y + p.rect().h]
            if not owners:
                continue
            owner = min(owners, key=lambda r: r.rect().w * r.rect().h)
            if owner.object_id() is None:
                continue
            out.append(DlsFaceCandidate(bbox=(int(fr.x), int(fr.y), int(fr.x + fr.w), int(fr.y + fr.h)), embedding=feature,
                                        detector_confidence=float(face.confidence()), track_id=int(owner.object_id())))
        return out

    label_to_id = {("person" if v == "pedestrian" else v): k for k, v in VEHICLE_CLASS_NAMES.items()}

    def results_from_json(sample):
        """Boxes, track ids and face vectors from the JSON that gvametaconvert (C) attached to the frame: the same
        fields her detections_from_sample and DlsFaceMetadataBridge read, without walking every region in Python."""
        from gstgva import VideoFrame
        from pipeline.types import Detection
        messages = list(VideoFrame(sample.get_buffer(), caps=sample.get_caps()).messages())
        objects = json.loads(messages[-1]).get("objects", []) if messages else []
        detections, people, faces = [], [], []
        for o in objects:
            label = (o.get("detection") or {}).get("label", "")
            x, y, w, h = int(o["x"]), int(o["y"]), int(o["w"]), int(o["h"])
            if label == "face":
                faces.append((o, (x, y, w, h)))
                continue
            class_id = label_to_id.get(label)
            if class_id is None:
                continue  # e.g. the model's "others" class, as in her bridge
            track_id = o.get("id")
            if track_id is None:
                raise RuntimeError("gvatrack did not attach a track ID")
            bbox = [x, y, x + w, y + h]
            detections.append(Detection(bbox=bbox, class_id=int(class_id), class_name=VEHICLE_CLASS_NAMES[class_id],
                                        confidence=float(o["detection"]["confidence"]), model_name="vehicle",
                                        metadata={"track_id": int(track_id), "raw_bbox": list(bbox), "predicted": False,
                                                  "tracker_backend": "gvatrack"}))
            if label == "person":
                people.append((int(track_id), x, y, w, h))
        candidates = []
        for o, (x, y, w, h) in faces:
            feature = None
            for tensor in o.get("tensors") or []:
                data = tensor.get("data")
                if data is not None and len(data) == 512:
                    feature = np.asarray(data, dtype=np.float32)
                    break
            if feature is None or not np.isfinite(feature).all() or float(np.linalg.norm(feature)) <= 1e-12:
                continue
            feature /= float(np.linalg.norm(feature))
            cx, cy = x + w / 2.0, y + h / 2.0
            owners = [p for p in people if p[1] <= cx <= p[1] + p[3] and p[2] <= cy <= p[2] + p[4]]
            if not owners:
                continue
            owner = min(owners, key=lambda p: p[3] * p[4])
            candidates.append(DlsFaceCandidate(bbox=(x, y, x + w, y + h), embedding=feature,
                                               detector_confidence=float(o["detection"]["confidence"]), track_id=owner[0]))
        return detections, candidates

    def write_frame(cam, sample, index):
        """Copy one NV12 frame (system memory) into the camera's next shared-memory slot; returns (name, slot, w, h)."""
        video = GstVideo.VideoInfo.new_from_caps(sample.get_caps())
        width, height = video.width, video.height
        size = event_worker.frame_bytes(width, height)
        if cam["shm"] is None or cam["shm_size"] != size:
            old = cam["shm"]
            cam["shm"] = shared_memory.SharedMemory(create=True, size=event_worker.SLOTS * (8 + size))
            cam["shm_size"] = size
            cam.setdefault("old_shm", []).append(old) if old is not None else None
            np.ndarray((event_worker.SLOTS,), dtype=np.int64, buffer=cam["shm"].buf)[:] = -1
        slot = cam["slot"] = (cam["slot"] + 1) % event_worker.SLOTS
        buf = cam["shm"].buf
        header = np.ndarray((event_worker.SLOTS,), dtype=np.int64, buffer=buf)
        header[slot] = -1
        dest = np.ndarray((height * 3 // 2, width), dtype=np.uint8, buffer=buf, offset=event_worker.SLOTS * 8 + slot * size)
        gbuf = sample.get_buffer()
        ok, info = gbuf.map(Gst.MapFlags.READ)
        if not ok:
            raise RuntimeError("NV12 map failed")
        try:
            data = np.frombuffer(info.data, dtype=np.uint8)
            y = data[video.offset[0]:video.offset[0] + video.stride[0] * height].reshape(height, video.stride[0])
            uv = data[video.offset[1]:video.offset[1] + video.stride[1] * (height // 2)].reshape(height // 2, video.stride[1])
            dest[:height] = y[:, :width]
            dest[height:] = uv[:, :width]
        finally:
            gbuf.unmap(info)
        header[slot] = index
        return cam["shm"].name, slot, width, height

    def unletterbox(detections, width, height, side=320):
        s = min(side / width, side / height)
        pad_x, pad_y = (side - width * s) / 2.0, (side - height * s) / 2.0
        for d in detections:
            x1, y1, x2, y2 = d.bbox
            d.bbox = [int(max(0, min(width, (x1 - pad_x) / s))), int(max(0, min(height, (y1 - pad_y) / s))),
                      int(max(0, min(width, (x2 - pad_x) / s))), int(max(0, min(height, (y2 - pad_y) / s)))]
        return detections

