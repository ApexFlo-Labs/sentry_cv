"""Integration prototype, version 3: our Option 5 inference engine + the Sentry V8 post-inference code (unchanged),
with each camera's event code in its OWN PROCESS (event_worker.py), so cameras do not wait on each other's Python.

Engine process (this file): one GStreamer graph, shared models (vehicle detector, gvatrack, SCRFD, AdaFace, fire),
rebuildable camera sources (only the source is rebuilt on a rejoin). At the end of each camera's main branch a tee
gives two appsinks with the same frames: evt (GPU frame + boxes, track ids, face vectors) and pix (the same frame
converted on the GPU to NV12 in system memory). A light reader thread per camera turns the boxes into her Detection
objects, copies the NV12 frame into a ring of slots in shared memory and queues a small message for the camera's
event process. Fire boxes come from a 2 fps 320x320 branch and are mapped back to full size.

Event processes: her V8EventPipeline, face pipeline, tracker stage, body/gait/scene/pose models, per camera; they
convert a frame to BGR only when her code asks for pixels. Her handoff scheduler runs here and each camera process
holds its own connection to it (as in her runtime), delivering to the agent on SENTINEL_DELIVERY_AGENT_SOCKET.

Not in this prototype: plates/ANPR, the frozen-picture check, the HTTP health endpoints.
Usage: integrate2.py desired_state.json [duration_seconds]
"""
