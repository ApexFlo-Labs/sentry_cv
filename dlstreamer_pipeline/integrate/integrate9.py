    cg.creader_new.restype = ctypes.c_void_p
    cg.creader_new.argtypes = [ctypes.c_void_p] + [ctypes.c_long] * 6
    cg.creader_attach.argtypes = [ctypes.c_void_p] * 4
    cg.creader_attach_in.argtypes = [ctypes.c_void_p] * 2
